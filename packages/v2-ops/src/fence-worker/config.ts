// Derives the fence Worker's wrangler config from the legacy Worker's wrangler.jsonc, so the two cannot drift: the same name, compatibility
// date, Durable Object bindings, migrations, containers, R2 buckets, KV namespace and version metadata, with only `main` replaced and what an
// inert Worker has no use for (static assets, Workers AI, rate limits, the web build, preview settings) removed. Nothing is deleted from the
// namespaces: no `deleted_classes`, no `exports` tombstone, and the migrations array is carried over unchanged.

/** Removes // and /* *\/ comments and trailing commas from JSONC, leaving string contents alone. */
export function parseJsonc(text: string): any {
	let out = "";
	let inString = false;
	for (let i = 0; i < text.length; i++) {
		const c = text[i]!;
		if (inString) {
			out += c;
			if (c === "\\") out += text[++i] ?? "";
			else if (c === '"') inString = false;
		} else if (c === '"') {
			inString = true;
			out += c;
		} else if (c === "/" && text[i + 1] === "/") {
			while (i < text.length && text[i] !== "\n") i++;
			out += "\n";
		} else if (c === "/" && text[i + 1] === "*") {
			i += 2;
			while (i < text.length && !(text[i] === "*" && text[i + 1] === "/")) i++;
			i++;
		} else out += c;
	}
	return JSON.parse(out.replace(/,(\s*[}\]])/g, "$1"));
}

const DROPPED = ["assets", "ai", "build", "ratelimits", "previews", "send_email", "$schema", "triggers", "routes", "route"];

/**
 * `legacyDir` and `fenceDir` locate the two configs relative to the repository root so that paths in the containers block (a Dockerfile and
 * its build context) still point at the same files from the fence config's directory.
 */
export function fenceConfig(legacy: any, options: { relativeRoot: string; main: string }): any {
	const config: any = {};
	for (const [key, value] of Object.entries(legacy)) if (!DROPPED.includes(key)) config[key] = structuredClone(value);
	config.main = options.main;
	config.name = legacy.name;
	for (const container of config.containers ?? []) {
		for (const image of Object.values<any>(container.images ?? {})) {
			if (image.dockerfile) image.dockerfile = `${options.relativeRoot}/${String(image.dockerfile).replace(/^\.\//, "")}`;
			if (image.build_context) image.build_context = `${options.relativeRoot}/${String(image.build_context).replace(/^\.\//, "")}`;
		}
	}
	config.workers_dev = false;
	config.vars = { ...(legacy.vars ?? {}) };
	return config;
}

