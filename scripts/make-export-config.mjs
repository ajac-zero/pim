#!/usr/bin/env node
// Writes wrangler.export.jsonc, the maintenance/export Worker's configuration, from wrangler.jsonc: the same
// durable object bindings, migrations, containers, KV and R2 (so no namespace or data is touched), a different entry,
// and none of the product's assets, build or model binding. Re-run it after wrangler.jsonc changes; a test compares the two.
import { readFileSync, writeFileSync } from "node:fs";

/** wrangler.jsonc as an object: comments and trailing commas removed. */
export function readJsonc(path) {
	const text = readFileSync(path, "utf8");
	let out = "";
	let inString = false;
	for (let i = 0; i < text.length; i++) {
		const c = text[i];
		if (inString) {
			out += c;
			if (c === "\\") out += text[++i];
			else if (c === '"') inString = false;
		} else if (c === '"') {
			inString = true;
			out += c;
		} else if (c === "/" && text[i + 1] === "/") while (i < text.length && text[i] !== "\n") i++;
		else if (c === "/" && text[i + 1] === "*") {
			i += 2;
			while (!(text[i] === "*" && text[i + 1] === "/")) i++;
			i++;
		} else out += c;
	}
	return JSON.parse(out.replace(/,(\s*[}\]])/g, "$1"));
}

export function exportConfig(product) {
	return {
		$schema: "./node_modules/wrangler/config-schema.json",
		// The same Worker name: Durable Object namespaces belong to the script, so only a new version of this Worker reaches the existing objects.
		name: product.name,
		main: "export-worker/worker.ts",
		compatibility_date: product.compatibility_date,
		compatibility_flags: product.compatibility_flags,
		workers_dev: false,
		durable_objects: product.durable_objects,
		migrations: product.migrations,
		containers: product.containers,
		kv_namespaces: product.kv_namespaces,
		r2_buckets: product.r2_buckets,
		version_metadata: product.version_metadata,
		observability: { enabled: true },
	};
}

if (import.meta.url === `file://${process.argv[1]}`) {
	writeFileSync("wrangler.export.jsonc", `// Generated by scripts/make-export-config.mjs from wrangler.jsonc. The maintenance/export Worker: nothing here is deployed by CI.\n${JSON.stringify(exportConfig(readJsonc("wrangler.jsonc")), null, 2)}\n`);
}
