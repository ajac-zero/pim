#!/usr/bin/env node
// Builds docs/architecture/v2-inventory-coverage.md: one row per inventory entry (every `###` heading of inventory/B1..B6), from rules.mjs.
// Fails when an entry has no rule, so a new or renamed entry cannot go unmapped. `--check` compares the committed file instead of writing it.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { RULES } from "./rules.mjs";

const dir = new URL("../../docs/architecture/inventory/", import.meta.url);
const out = new URL("../../docs/architecture/v2-inventory-coverage.md", import.meta.url);
const files = readdirSync(dir).filter((f) => /^B[1-6]-/.test(f)).sort();
const rows = [];
const unmapped = [];
for (const file of files) {
	const group = file.slice(0, 2);
	const lines = readFileSync(new URL(file, dir), "utf8").split("\n");
	let n = 0;
	lines.forEach((line, i) => {
		const m = /^### (.+)$/.exec(line);
		if (!m) return;
		const heading = m[1].trim();
		const rule = RULES.find(([g, re]) => g === group && re.test(heading));
		const id = `${group}.${String(++n).padStart(2, "0")}`;
		if (!rule) return unmapped.push(`${id} ${heading}`);
		const [, , change, authority, tests, status, note] = rule;
		rows.push({ id, heading, line: i + 1, file, change, authority, tests, status, note });
	});
}
if (unmapped.length) {
	console.error(`Entries with no rule:\n${unmapped.join("\n")}`);
	process.exit(1);
}
// A test a row names must exist.
const missing = rows.flatMap((r) => r.tests.split(", ").filter((t) => /^v2-[a-z]+\/test\//.test(t) && !existsSync(new URL(`../../packages/${t}`, import.meta.url))).map((t) => `${r.id}: ${t}`));
if (missing.length) {
	console.error(`Tests that do not exist:\n${missing.join("\n")}`);
	process.exit(1);
}
const count = (s) => rows.filter((r) => r.status === s).length;
const esc = (t) => t.replaceAll("|", "\\|");
const md = [
	"# v2 inventory coverage",
	"",
	"Generated by `node scripts/v2-coverage/build.mjs` from the `###` headings of [inventory/B1..B6](inventory/) and the judgments in `scripts/v2-coverage/rules.mjs`; do not edit by hand. The script fails when an entry has no rule, and `test/v2-coverage.node.test.ts` fails when this file is out of date.",
	"",
	`**${rows.length} entries.** Verified ${count("Verified")}, Partial ${count("Partial")}, Gap ${count("Gap")}, Not behaviour (analysis) ${count("N/A")}.`,
	"",
	"- **Verified:** an automated test exercises the entry's v2 behaviour in sandbox tests on the real stack (real PostgreSQL; with NATS, S3, WebSockets or processes where the entry needs them). It is **not** full live production parity: nothing here ran on Docker, a cluster, a third-party sign-in or a production-sized load, and the judgment is about the entry as a whole, not a claim that every sentence of the entry has an assertion.",
	"- **Partial:** implemented, with the part that is untested or missing in the note.",
	"- **Gap:** v2 does not carry it.",
	"- Tests are paths under `packages/`.",
	"",
	"## Every Gap, plainly",
	"",
	...rows.filter((r) => r.status === "Gap").map((r) => `- **${r.id}** ${esc(r.heading)}${r.note ? `: ${esc(r.note)}` : ""}`),
	"",
	"## All entries",
	"",
	"| Entry | Inventory heading | Behavior | v2 authority | Tests | Status | Note |",
	"|---|---|---|---|---|---|---|",
	...rows.map((r) => `| ${r.id} | [${esc(r.heading)}](inventory/${r.file}#L${r.line}) | ${r.change} | ${esc(r.authority)} | ${esc(r.tests)} | ${r.status} | ${esc(r.note)} |`),
	"",
].join("\n");
if (process.argv.includes("--check")) {
	if (readFileSync(out, "utf8") !== md) {
		console.error("docs/architecture/v2-inventory-coverage.md is out of date: run node scripts/v2-coverage/build.mjs");
		process.exit(1);
	}
} else writeFileSync(out, md);
console.log(`${rows.length} entries: ${count("Verified")} verified, ${count("Partial")} partial, ${count("Gap")} gap, ${count("N/A")} not behaviour`);
