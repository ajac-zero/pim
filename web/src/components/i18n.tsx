export type TranslationKey = keyof (typeof translations)["en"];
type Variables = Record<string, string | number>;

function supportedLocale(value: string | null | undefined): Locale | null {
  const language = value?.toLowerCase().split("-")[0];
  return locales.find((locale) => locale === language) ?? null;
}

function initialLocale(): Locale {
  if (typeof window === "undefined") return "en";
  return (
    supportedLocale(window.localStorage.getItem(STORAGE_KEY)) ??
    supportedLocale(window.navigator.language) ??
    "en"
  );
}

function interpolate(message: string, values?: Variables): string {
  return message.replace(/\{(\w+)\}/g, (_, name: string) =>
    values?.[name] === undefined ? `{${name}}` : String(values[name]),
  );
}

export interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, values?: Variables) => string;
  formatDate: (date: Date, options?: Intl.DateTimeFormatOptions) => string;
  formatNumber: (value: number, options?: Intl.NumberFormatOptions) => string;
}

/** The words and formats of one language, outside React as well as in it. */
export function i18nFor(locale: Locale): I18nContextValue {
  return {
    locale,
    setLocale: () => {},
    t: (key, values) => interpolate(translations[locale][key], values),
    formatDate: (date, options) =>
      new Intl.DateTimeFormat(locale, options).format(date),
    formatNumber: (number, options) =>
      new Intl.NumberFormat(locale, options).format(number),
  };
}

const I18nContext = createContext<I18nContextValue>(i18nFor("en"));

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);
  const queryClient = useQueryClient();
  const { data: signedIn } = useQuery(signedInQuery());
  const { data: settings } = useQuery(appearanceQueries(signedIn === true));

  // The language the person chose on any device wins over this browser's own.
  const serverLocale = settings?.locale;
  useEffect(() => {
    if (!serverLocale) return;
    setLocaleState(serverLocale);
    window.localStorage.setItem(STORAGE_KEY, serverLocale);
  }, [serverLocale]);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = (nextLocale: Locale) => {
    setLocaleState(nextLocale);
    window.localStorage.setItem(STORAGE_KEY, nextLocale);
    saveAppearance(queryClient, { locale: nextLocale });
  };

  const value: I18nContextValue = { ...i18nFor(locale), setLocale };

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}

/** The app's language, a setting of this browser, as a field in Settings. */
export function LanguageSelect() {
  const { locale, setLocale, t } = useI18n();
  return (
    <label className="flex flex-col gap-2 rounded-2xl border bg-muted/20 px-4 py-4">
      <span className="text-muted-foreground text-[13px]">{t("language")}</span>
      <select
        value={locale}
        onChange={(event) => setLocale(event.target.value as Locale)}
        className="h-10 w-full rounded-xl border bg-background px-3 text-sm"
      >
        <option value="en">{t("english")}</option>
        <option value="es">{t("spanish")}</option>
      </select>
    </label>
  );
}
